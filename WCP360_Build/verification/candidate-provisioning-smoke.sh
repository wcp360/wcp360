#!/usr/bin/env bash
set -Eeuo pipefail
[[ "$(id -u)" == 0 ]] || exit 78
# The Go guard independently checks root-owned boot-bound VM evidence or the container profile.
if [[ "${WCP_ISOLATED_TEST_VM:-}" == 1 && -z "${WCP_ISOLATED_TEST_CONTAINER:-}" && ! -e /.dockerenv ]]; then
    profile=vm
elif [[ "${WCP_ISOLATED_TEST_CONTAINER:-}" == 1 && -z "${WCP_ISOLATED_TEST_VM:-}" && -f /.dockerenv ]]; then
    profile=container
else
    echo "Explicit disposable execution profile required." >&2; exit 78
fi
# Invoking an unknown mode first runs the real Go environment guard without effects.
set +e
/usr/local/libexec/wcp360/wcp-candidate-node guard-check --agent-uid 31002 --worker-uid 31003 --ipc-gid 31004
status=$?
set -e
[[ "$status" == 2 ]] || { echo "Execution guard rejected." >&2; exit 78; }
cd /opt/wcp360/WCP360_Core
node_binary=/usr/local/libexec/wcp360/wcp-candidate-node
broker_pid=
agent_pid=
cleanup(){
    status=$?
    trap - EXIT
    [[ -z "$agent_pid" ]] || kill "$agent_pid" 2>/dev/null || true
    [[ -z "$broker_pid" ]] || kill "$broker_pid" 2>/dev/null || true
    if (( status != 0 )); then
        cat /tmp/wcp-broker.log /tmp/wcp-agent.log /var/lib/wcp360-provision-candidate/*error.log 2>/dev/null || true
        if [[ "${WCP_CANDIDATE_SYSTEMD:-}" == 1 ]]; then
            systemctl show wcp-candidate-broker -p MainPID -p CapabilityBoundingSet -p AmbientCapabilities -p NoNewPrivileges -p SystemCallFilter -p RestrictSUIDSGID -p SecureBits
            main_pid="$(systemctl show -p MainPID --value wcp-candidate-broker)"
            if [[ "$main_pid" =~ ^[1-9][0-9]*$ ]]; then
                for candidate_pid in "$main_pid" $(pgrep -P "$main_pid" || true); do
                    printf 'DIAGNOSTIC: process %s\n' "$candidate_pid"
                    awk '/^(Name|Uid|Gid|CapInh|CapPrm|CapEff|CapBnd|CapAmb|NoNewPrivs|Seccomp):/' "/proc/$candidate_pid/status" || true
                    cat "/proc/$candidate_pid/attr/current" 2>/dev/null || true
                done
            fi
            journalctl --no-pager -u wcp-candidate-broker -u wcp-candidate-agent -n 60; systemctl stop wcp-candidate-agent wcp-candidate-broker; fi
    fi
    exit "$status"
}
trap cleanup EXIT
groupadd --gid 31002 wcp-agent-test
groupadd --gid 31003 wcp-worker-test
groupadd --gid 31004 wcp-ipc-test
useradd --uid 31002 --gid 31002 --no-create-home --shell /usr/sbin/nologin wcp-agent-test
useradd --uid 31003 --gid 31003 --no-create-home --shell /usr/sbin/nologin wcp-worker-test
usermod -aG wcp-ipc-test wcp-agent-test
usermod -aG wcp-ipc-test wcp-worker-test
# Dedicated cache, sessions and SQLite fixture belong only to the unprivileged worker.
worker_dir=/tmp/wcp-worker-test
if [[ "$profile" == vm && "${WCP_CANDIDATE_SYSTEMD:-}" == 1 ]]; then worker_dir=/var/lib/wcp360-candidate-test-worker; fi
install -d -o 31003 -g 31003 -m 0700 "$worker_dir"
export APP_ENV=test APP_DEBUG=1 APP_SECRET=provision-test-only-secret WCP_CANDIDATE=1 WCP_CONTEXT=worker WCP_PUBLIC_HOST=localhost WCP_ALLOW_ISOLATED_PROVISIONING=1 WCP_PLANNER=/usr/local/libexec/wcp360/wcp-plan
export DATABASE_URL="sqlite:///$worker_dir/workbench.db"
# Test kernel cache is generated by this worker in the disposable container.
install -d -o 31003 -g 31003 -m 0700 var/cache/test/worker var/log
runuser -u wcp-worker-test -- php /opt/wcp360/WCP360_Build/verification/candidate-provisioning-fixture.php seed
if [[ "$profile" == vm && "${WCP_CANDIDATE_SYSTEMD:-}" == 1 ]]; then
    # Explicit opt-in is created only in this already-guarded disposable guest.
    install -d -m 0700 /etc/wcp360-candidate
    { printf 'wcp360.candidate.vm-recovery/1\n'; cat /etc/machine-id; } >/etc/wcp360-candidate/allow-boot-recovery
    chmod 0600 /etc/wcp360-candidate/allow-boot-recovery
    for name in vm-arm broker agent; do
        install -m 0644 "resources/services/systemd/candidate/wcp-candidate-$name.service" "/etc/systemd/system/wcp-candidate-$name.service"
    done
    systemd-analyze verify /etc/systemd/system/wcp-candidate-{vm-arm,broker,agent}.service
    systemctl daemon-reload
    systemctl enable --now wcp-candidate-vm-arm wcp-candidate-broker wcp-candidate-agent
else
"$node_binary" broker --agent-uid 31002 --worker-uid 31003 --ipc-gid 31004 >/tmp/wcp-broker.log 2>&1 &
broker_pid=$!
for attempt in {1..40}; do [[ ! -S /run/wcp360-provision-candidate/broker.sock ]] || break; kill -0 "$broker_pid"; sleep 0.1; done
runuser -u wcp-agent-test -- "$node_binary" agent --agent-uid 31002 --worker-uid 31003 --ipc-gid 31004 >/tmp/wcp-agent.log 2>&1 &
agent_pid=$!
for attempt in {1..40}; do [[ ! -S /run/wcp360-provision-candidate/public/agent.sock ]] || break; kill -0 "$agent_pid"; sleep 0.1; done
fi
runuser -u wcp-worker-test -- php /opt/wcp360/WCP360_Build/verification/candidate-provisioning-fixture.php run
php -r '$rows=json_decode(file_get_contents("/tmp/wcp-provision-requests.json"),true,16,JSON_THROW_ON_ERROR);foreach($rows as $r){$ctx=stream_context_create(["http"=>["header"=>"Host: ".$r["hostname"]."\r\n","timeout"=>5]]);$body=json_decode(file_get_contents("http://127.0.0.1:8080/__wcp_probe.php",false,$ctx),true,8,JSON_THROW_ON_ERROR);if($body["site_id"]!==$r["site_id"]||$body["tenant_id"]!==$r["tenant_id"]||$body["euid"]===0)exit(1);}'
php /opt/wcp360/WCP360_Build/verification/candidate-demo-application-smoke.php
# Inspect uncertain application state; never resend the provisioning operation.
runuser -u wcp-worker-test -- php /opt/wcp360/WCP360_Build/verification/candidate-provisioning-fixture.php reconcile
mapfile -t site_ids < <(php -r 'foreach(json_decode(file_get_contents("/tmp/wcp-provision-requests.json"),true,16,JSON_THROW_ON_ERROR)as $r)echo $r["site_id"]."\n";')
user_one="wcp_$(printf '%s' "${site_ids[0]}" | sha256sum | cut -c1-24)"
user_two="wcp_$(printf '%s' "${site_ids[1]}" | sha256sum | cut -c1-24)"
printf 'private fixture\n' >"/srv/wcp360-candidate/vhosts/${site_ids[1]}/var/private.txt"
runuser -u "$user_one" -- test ! -r "/srv/wcp360-candidate/vhosts/${site_ids[1]}/var/private.txt"
runuser -u "$user_two" -- test ! -r "/srv/wcp360-candidate/vhosts/${site_ids[0]}/public/index.php"
# Even root is rejected as an IPC caller; the socket trusts only the configured peer UID.
php -r '$s=stream_socket_client("unix:///run/wcp360-provision-candidate/broker.sock");stream_socket_shutdown($s,STREAM_SHUT_WR);$r=json_decode(stream_get_contents($s),true,8,JSON_THROW_ON_ERROR);if($r["status"]!=="REJECTED")exit(1);fclose($s);'
# A whitelisted worker cannot smuggle generic commands through the unprivileged agent.
runuser -u wcp-worker-test -- php -r '$s=stream_socket_client("unix:///run/wcp360-provision-candidate/public/agent.sock");fwrite($s,"{\"operation\":\"shell.exec\",\"command\":\"id\"}");stream_socket_shutdown($s,STREAM_SHUT_WR);$r=json_decode(stream_get_contents($s),true,8,JSON_THROW_ON_ERROR);if($r["status"]!=="REJECTED")exit(1);fclose($s);'
[[ "$(find /var/lib/wcp360-provision-candidate/records -name '*.json' -type f | wc -l)" == 2 ]]
[[ "$(curl -sS -o /dev/null -w '%{http_code}' -H 'Host: alice.test' http://127.0.0.1:8080/.secret)" == 403 ]]
printf 'PASS: disposable %s; Symfony durable jobs -> unprivileged agent -> root broker -> two real isolated PHP-FPM sites; inspection and peer/schema rejection and stateful packaged application verified.\n' "$profile"
